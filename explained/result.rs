/// カスタムResult型の定義
/// 
/// # 設計思想
/// OSの低レベル開発では、複雑なエラー型よりもシンプルで軽量な
/// エラーハンドリングが求められます。この型定義は以下の特徴を持ちます：
/// 
/// - エラー型: `&'static str` - コンパイル時に決定される文字列
/// - メモリ効率: 動的メモリ確保を必要としない
/// - 簡潔性: エラーメッセージが直接的で理解しやすい
/// 
/// # 使用例
/// ```rust
/// use crate::result::Result;
/// 
/// fn divide(a: i32, b: i32) -> Result<i32> {
///     if b == 0 {
///         Err("Division by zero")
///     } else {
///         Ok(a / b)
///     }
/// }
/// 
/// match divide(10, 2) {
///     Ok(result) => println!("Result: {}", result),
///     Err(msg) => println!("Error: {}", msg),
/// }
/// ```
/// 
/// # エラーメッセージのガイドライン
/// このResult型を使用する際は、以下のガイドラインに従ってください：
/// 
/// 1. **簡潔性**: エラーメッセージは短く、要点を明確に
///    - 良い例: "Out of Range"
///    - 悪い例: "The provided coordinates are outside the valid range"
/// 
/// 2. **一貫性**: 同種のエラーには統一されたメッセージを使用
///    - メモリ関連: "Memory allocation failed"
///    - 範囲外アクセス: "Out of Range" 
///    - 無効な引数: "Invalid argument"
/// 
/// 3. **国際化非対応**: 開発者向けメッセージのため英語で統一
/// 
/// # `&'static str`を選択する理由
/// 
/// ## 利点
/// - **ゼロコスト**: 実行時オーバーヘッドなし
/// - **メモリ安全**: 静的文字列なのでダングリングポインタのリスクなし
/// - **コンパイル時最適化**: リンカーによる文字列の重複排除が可能
/// - **no_std対応**: ヒープメモリを使用しない
/// 
/// ## 制約
/// - 動的なエラー情報（数値など）を含められない
/// - 実行時にエラーメッセージを生成できない
/// - 国際化（i18n）に対応していない
/// 
/// # OSカーネル開発での適用例
/// 
/// ```rust
/// // グラフィック描画でのエラーハンドリング
/// fn draw_pixel(x: i64, y: i64) -> Result<()> {
///     if x < 0 || y < 0 {
///         return Err("Negative coordinates");
///     }
///     if x >= SCREEN_WIDTH || y >= SCREEN_HEIGHT {
///         return Err("Out of Range");
///     }
///     // 描画処理...
///     Ok(())
/// }
/// 
/// // メモリ管理でのエラーハンドリング
/// fn allocate_pages(count: usize) -> Result<*mut u8> {
///     if count == 0 {
///         return Err("Invalid page count");
///     }
///     if count > MAX_PAGES {
///         return Err("Too many pages requested");
///     }
///     // メモリ確保処理...
///     Ok(ptr)
/// }
/// ```
/// 
/// # 将来的な拡張性
/// 
/// プロジェクトが成長するにつれて、より詳細なエラー情報が必要になる
/// 可能性があります。その場合は以下のような拡張を検討できます：
/// 
/// ```rust
/// // より詳細なエラー型への移行例
/// #[derive(Debug)]
/// enum Error {
///     OutOfRange { x: i64, y: i64, max_x: i64, max_y: i64 },
///     MemoryAllocation { requested: usize, available: usize },
///     InvalidArgument(&'static str),
/// }
/// 
/// pub type Result<T> = core::result::Result<T, Error>;
/// ```
/// 
/// ただし、OSカーネルレベルでは、シンプルな文字列エラーで
/// 十分な場合が多く、現在の設計が適切です。
pub type Result<T> = core::result::Result<T, &'static str>;

