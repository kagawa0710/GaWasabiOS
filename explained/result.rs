// =============================================================================
// 設計判断の記録
// =============================================================================
//
// 1. なぜ`&'static str`を選択したか
//    - no_std環境での軽量性
//    - コンパイル時エラーチェック
//    - メモリ使用量の予測可能性
//
// 2. なぜ複雑なエラー型を避けたか
//    - カーネル開発の初期段階では過度な抽象化は不要
//    - デバッグ時にエラーメッセージが直感的
//    - パフォーマンスへの影響を最小限に抑制
//
// 3. 将来の拡張性への配慮
//    - 型エイリアスによる変更コストの最小化
//    - モジュール分離による影響範囲の限定
//    - 段階的な移行が可能な設計