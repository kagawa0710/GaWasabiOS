/// 標準ライブラリの無効化
/// 
/// OSカーネル開発では、標準ライブラリ（std）は使用できません。
/// これは以下の理由によります：
/// 
/// 1. **ヒープメモリの不在**: stdはヒープアロケータを前提とするが、
///    カーネル初期化段階ではまだ利用できない
/// 2. **システムコールの未実装**: stdの多くの機能はOSのシステムコール
///    に依存するが、カーネル自体がその実装者
/// 3. **実行環境の制約**: ユーザーランドとは異なる実行コンテキスト
/// 
/// 代わりにcore（no_std環境用コアライブラリ）を使用します。
#![no_std]

/// 実験的な機能の有効化: offset_of
/// 
/// `offset_of!`マクロを使用するために必要なfeature gateです。
/// このマクロは構造体のメンバーのメモリオフセットを
/// コンパイル時に計算するために使用されます。
/// 
/// # 使用例（UEFI構造体での用途）
/// ```rust
/// use core::mem::offset_of;
/// 
/// #[repr(C)]
/// struct EfiTableHeader {
///     signature: u64,
///     revision: u32,
///     header_size: u32,
///     crc32: u32,
/// }
/// 
/// // revisionメンバーのオフセットを取得
/// let revision_offset = offset_of!(EfiTableHeader, revision);
/// ```
/// 
/// # OSカーネル開発での重要性
/// - **ABI互換性**: UEFI等の外部インターフェースとの正確な構造体レイアウト
/// - **メモリマップ**: ハードウェアレジスタや固定アドレスへの安全なアクセス
/// - **低レベル最適化**: コンパイル時計算によるランタイムオーバーヘッドの回避
#![feature(offset_of)]

