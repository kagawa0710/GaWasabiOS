/// グラフィック描画システム
/// 
/// VRAM（ビデオRAM）への低レベル描画機能を提供します。
/// - ビットマップ操作の抽象化
/// - 基本図形描画（点、線、矩形）
/// - フォントレンダリング
/// - テストパターン生成
/// 
/// # 設計原則
/// - **ハードウェア非依存**: Bitmapトレイトによる抽象化
/// - **型安全性**: ジェネリクスとトレイトによるコンパイル時検証
/// - **パフォーマンス重視**: unsafe操作も選択可能
/// 
/// # 主な公開API
/// - `Bitmap`トレイト: 描画対象の抽象化
/// - `fill_rect()`: 矩形塗りつぶし
/// - `draw_font_fg()`: 単一文字描画
/// - `draw_test_pattern()`: デバッグ用パターン
pub mod graphics;

/// エラーハンドリング型定義
/// 
/// プロジェクト全体で統一されたエラーハンドリング機構を提供します。
/// シンプルで軽量な`Result<T>`型により、no_std環境での
/// 効率的なエラー処理を実現します。
/// 
/// # 特徴
/// - **軽量性**: `&'static str`によるゼロコストエラー
/// - **一貫性**: 全モジュールで統一されたエラー型
/// - **明確性**: 直感的なエラーメッセージ
/// 
/// # 主な公開API
/// - `Result<T>`: 統一エラーハンドリング型
pub mod result;

/// UEFI（Unified Extensible Firmware Interface）インターフェース
/// 
/// 現代的なPCファームウェアとの相互運用性を提供します。
/// BIOSの後継であるUEFIの各種サービスへのアクセス機能を実装。
/// 
/// # 提供機能
/// - システム情報の取得
/// - グラフィック出力プロトコル
/// - メモリマップの獲得
/// - ファイルシステムアクセス（将来的）
/// 
/// # 注意事項
/// このモジュールは現在実装中です。UEFIの複雑性により、
/// 段階的な実装が進行中です。
/// 
/// # 主な公開API（予定）
/// - UEFI構造体定義
/// - プロトコルアクセス関数
/// - システムサービス呼び出し
pub mod uefi;

// =============================================================================
// ライブラリ設計思想とアーキテクチャ原則
// =============================================================================

// 1. **モジュラー設計**
//    各機能を独立したモジュールに分離し、相互依存を最小限に抑制。
//    これにより、個別のテストとメンテナンスが容易になります。
//
// 2. **抽象化レベルの階層化**
//    - 低レベル（uefi）: ハードウェア・ファームウェア直接アクセス
//    - 中レベル（graphics）: ハードウェア非依存の描画システム
//    - 高レベル（result）: アプリケーション層のユーティリティ
//
// 3. **no_std制約への対応**
//    - 標準ライブラリなしでの開発
//    - ヒープメモリ使用の回避
//    - コンパイル時計算の活用
//
// 4. **型安全性の重視**
//    - Rustの型システムを活用した安全性確保
//    - unsafeコードの明示的な分離と最小化
//    - トレイトによる抽象化でバグの早期発見
//
// 5. **パフォーマンス重視**
//    - ゼロコスト抽象化の活用
//    - インライン化とコンパイル時最適化
//    - メモリアクセスパターンの最適化

